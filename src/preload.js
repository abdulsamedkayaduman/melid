'use strict';
const { contextBridge, ipcRenderer, webUtils } = require('electron');

const inv = (ch) => (...a) => ipcRenderer.invoke(ch, ...a);
const on = (ch) => (fn) => {
  const l = (_e, ...a) => fn(...a);
  ipcRenderer.on(ch, l);
  return () => ipcRenderer.removeListener(ch, l);
};

contextBridge.exposeInMainWorld('api', {
  init: inv('app:init'),
  sessions: {
    save: inv('sessions:save'),
    remove: inv('sessions:delete'),
    renameGroup: inv('sessions:renameGroup'),
    deleteGroup: inv('sessions:deleteGroup'),
    importSshConfig: inv('sessions:importSshConfig'),
    import: inv('sessions:import'),
  },
  saveSettings: inv('settings:save'),
  master: {
    status: inv('master:status'),
    unlock: inv('master:unlock'),
    lock: inv('master:lock'),
    set: inv('master:set'),
  },
  backup: {
    export: inv('backup:export'),
    import: inv('backup:import'),
  },
  ssh: {
    connect: inv('ssh:connect'),
    shell: inv('ssh:shell'),
    closeShell: inv('ssh:closeShell'),
    cwd: inv('ssh:cwd'),
    stats: inv('ssh:stats'),
    installKey: inv('ssh:installKey'),
    write: (id, d, sid) => ipcRenderer.send('ssh:write', id, d, sid),
    resize: (id, c, r, sid) => ipcRenderer.send('ssh:resize', id, c, r, sid),
    disconnect: inv('ssh:disconnect'),
    forwardStart: inv('ssh:forwardStart'),
    forwardStop: inv('ssh:forwardStop'),
    forwardList: inv('ssh:forwardList'),
    onStatus: on('ssh:status'),
    onData: on('ssh:data'),
    onExit: on('ssh:exit'),
    onBanner: on('ssh:banner'),
    onForward: on('ssh:forward'),
  },
  sftp: {
    home: inv('sftp:home'),
    realpath: inv('sftp:realpath'),
    list: inv('sftp:list'),
    mkdir: inv('sftp:mkdir'),
    rename: inv('sftp:rename'),
    remove: inv('sftp:remove'),
    chmod: inv('sftp:chmod'),
    exists: inv('sftp:exists'),
    edit: inv('sftp:edit'),
    preview: inv('sftp:preview'),
    compare: inv('sync:compare'),
    transfer: inv('sftp:transfer'),
    cancel: inv('sftp:cancel'),
    onTransfer: on('sftp:transfer'),
    onEdit: on('edit:event'),
  },
  local: {
    list: inv('local:list'),
    mkdir: inv('local:mkdir'),
    rename: inv('local:rename'),
    remove: inv('local:remove'),
    exists: inv('local:exists'),
    open: inv('local:open'),
    reveal: inv('local:reveal'),
    resolve: inv('local:resolve'),
    preview: inv('local:preview'),
  },
  drag: {
    prepare: inv('drag:prepare'),
    start: (files) => ipcRenderer.send('drag:start', files),
  },
  keys: { list: inv('keys:list'), generate: inv('keys:generate') },
  logs: { dir: inv('logs:dir'), open: inv('logs:open') },
  clipboard: { read: inv('clipboard:read'), write: inv('clipboard:write') },
  openFileDialog: inv('dialog:openFile'),
  openDirDialog: inv('dialog:openDir'),
  onResume: on('app:resume'),
  onToast: on('app:toast'),
  onSessionsUpdated: on('sessions:updated'),
  update: {
    state: inv('update:state'),
    check: inv('update:check'),
    install: inv('update:install'),
    cancel: inv('update:cancel'),
    skip: inv('update:skip'),
    schedule: inv('update:schedule'),
    onAvailable: on('update:available'),
    onShow: on('update:show'),
    onProgress: on('update:progress'),
  },
  openExternal: inv('shell:openExternal'),
  pathForFile: (f) => webUtils.getPathForFile(f),
  onUiRequest: on('ui:request'),
  uiRespond: (id, value) => ipcRenderer.send('ui:response', { id, value }),
});
